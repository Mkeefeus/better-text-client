import { batch, createSignal } from 'solid-js';
import type { Message, MessageCategory, Span } from './types';

// The scrollback is a plain, mutable array. Signals only announce "it changed".
// Messages are immutable once created, so rows never need to re-render themselves.
//
// Incoming messages are queued and flushed at most once per animation frame, so a
// burst of hundreds of messages (e.g. right after connecting) costs one update.

const MAX_MESSAGES = 5000;
/** Trim in chunks, not one at a time: every front-trim shifts all indices. */
const TRIM_SLACK = 500;
/** Fallback flush delay for when the window is hidden and rAF is paused. */
const FLUSH_FALLBACK_MS = 250;

const timeFormat = new Intl.DateTimeFormat([], {
  hour: '2-digit',
  minute: '2-digit',
  second: '2-digit',
  hour12: false,
});

const buffer: Message[] = [];
let queue: Message[] = [];
let nextId = 1;
let flushScheduled = false;

const [messages, setMessages] = createSignal<readonly Message[]>(buffer, { equals: false });
const [lastMessageId, setLastMessageId] = createSignal(0);

/** The scrollback. The array is mutated in place; read it inside a tracking scope to react to changes. */
export { messages, lastMessageId };

function flush() {
  flushScheduled = false;
  if (queue.length === 0) return;

  for (const message of queue) buffer.push(message);
  queue = [];

  if (buffer.length > MAX_MESSAGES + TRIM_SLACK) {
    buffer.splice(0, buffer.length - MAX_MESSAGES);
  }

  batch(() => {
    setMessages(buffer);
    setLastMessageId(nextId - 1);
  });
}

function scheduleFlush() {
  if (flushScheduled) return;
  flushScheduled = true;
  // Whichever fires first wins; flush() is a no-op the second time.
  requestAnimationFrame(flush);
  setTimeout(flush, FLUSH_FALLBACK_MS);
}

export function pushMessage(category: MessageCategory, spans: Span[]) {
  queue.push({ id: nextId++, timeLabel: timeFormat.format(new Date()), category, spans });
  scheduleFlush();
}

/** A message generated by the client itself (status, errors), not by the server. */
export function pushClientMessage(category: 'client' | 'error', text: string) {
  pushMessage(category, [{ text, cls: '' }]);
}

export function clearMessages() {
  queue = [];
  buffer.length = 0;
  batch(() => {
    setMessages(buffer);
    setLastMessageId(nextId - 1);
  });
}
